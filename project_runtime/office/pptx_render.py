"""PPTX 渲染：markdown 或 JSON spec → python-pptx。"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def render_pptx_from_markdown(markdown: str, out_path: Path) -> dict[str, Any]:
    """沿用原 slide_generator 按节建页逻辑。"""
    from pptx import Presentation
    from pptx.util import Pt

    prs = Presentation()
    content_layout = prs.slide_layouts[1]
    h2_count = 0
    title_slide_added = False
    current_title: str | None = None
    body_lines: list[str] = []
    in_fence = False

    def flush_section(*, keep_title: str | None = None) -> None:
        nonlocal current_title, body_lines
        title = current_title
        if title is None and not body_lines:
            return
        slide = prs.slides.add_slide(content_layout)
        if title and hasattr(slide.shapes, "title") and slide.shapes.title:
            slide.shapes.title.text = title
        body_ph = None
        try:
            body_ph = slide.placeholders[1]
        except (KeyError, IndexError):
            for sh in slide.shapes:
                if sh.has_text_frame and sh != getattr(slide.shapes, "title", None):
                    body_ph = sh
                    break
        if body_ph is not None and body_lines:
            tf = body_ph.text_frame
            tf.clear()
            for i, line in enumerate(body_lines[:24]):
                p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
                text = line
                if text.startswith(("- ", "* ")):
                    text = text[2:]
                    p.level = 0
                p.text = text[:500]
                p.font.size = Pt(16)
        body_lines = []
        current_title = keep_title

    for raw in markdown.splitlines():
        stripped = raw.strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            if current_title is not None or body_lines:
                body_lines.append(stripped[:200])
            continue
        if in_fence:
            if current_title is not None or body_lines or title_slide_added:
                body_lines.append(stripped[:500] if stripped else "")
            continue
        if stripped == "---":
            flush_section(keep_title=None)
            continue
        if stripped.startswith("# ") and not stripped.startswith("## "):
            flush_section()
            slide = prs.slides.add_slide(prs.slide_layouts[0])
            slide.shapes.title.text = stripped[2:].strip()
            try:
                slide.placeholders[1].text = (
                    "autogenerated · Project Autonomous Agent"
                )
            except (KeyError, IndexError):
                pass
            title_slide_added = True
            current_title = None
            body_lines = []
            continue
        if stripped.startswith("## "):
            flush_section()
            h2_count += 1
            current_title = stripped[3:].strip()
            body_lines = []
            continue
        if not stripped:
            continue
        if current_title is None and not title_slide_added:
            current_title = "内容"
            h2_count += 1
        if current_title is None and title_slide_added:
            current_title = ""
        body_lines.append(stripped[:500])

    flush_section()
    if not title_slide_added and len(prs.slides._sldIdLst) == 0:  # noqa: SLF001
        slide = prs.slides.add_slide(prs.slide_layouts[0])
        slide.shapes.title.text = "演示文稿"
    prs.save(str(out_path))
    return _pptx_meta(out_path) | {"h2_count": h2_count}


def render_pptx_from_spec(spec: dict, out_path: Path) -> dict[str, Any]:
    """JSON: {title?, slides:[{title, bullets?:[], body?:str}]}."""
    from pptx import Presentation
    from pptx.util import Pt

    prs = Presentation()
    deck_title = str(spec.get("title") or "").strip()
    slides = spec.get("slides")
    if not isinstance(slides, list) or not slides:
        raise ValueError("spec.slides 必须为非空数组")

    if deck_title:
        cover = prs.slides.add_slide(prs.slide_layouts[0])
        cover.shapes.title.text = deck_title

    content_layout = prs.slide_layouts[1]
    for item in slides:
        if not isinstance(item, dict):
            continue
        title = str(item.get("title") or "").strip() or " "
        bullets = item.get("bullets") or []
        body = str(item.get("body") or "").strip()
        slide = prs.slides.add_slide(content_layout)
        if hasattr(slide.shapes, "title") and slide.shapes.title:
            slide.shapes.title.text = title
        lines: list[str] = []
        if isinstance(bullets, list):
            lines.extend(f"- {str(b)}" for b in bullets if str(b).strip())
        if body:
            lines.append(body)
        try:
            body_ph = slide.placeholders[1]
        except (KeyError, IndexError):
            body_ph = None
        if body_ph is not None and lines:
            tf = body_ph.text_frame
            tf.clear()
            for i, line in enumerate(lines[:24]):
                p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
                text = line[2:] if line.startswith("- ") else line
                p.text = text[:500]
                p.font.size = Pt(16)

    prs.save(str(out_path))
    return _pptx_meta(out_path) | {"h2_count": len(slides)}


def _pptx_meta(out_path: Path) -> dict[str, Any]:
    from pptx import Presentation as _Pres

    m = _Pres(str(out_path))
    slides = list(m.slides)
    non_empty = sum(
        1 for sl in slides
        if any(sh.has_text_frame and sh.text_frame.text.strip() for sh in sl.shapes)
    )
    has_title = bool(
        slides and any(
            sh.has_text_frame and sh.text_frame.text.strip()
            for sh in slides[0].shapes
        )
    )
    return {
        "slides": len(slides),
        "non_empty_slides": non_empty,
        "has_title_text": has_title,
    }


def load_spec(payload: dict, ws_root: Path | None) -> dict | str | None:
    """返回 dict(spec) / str(markdown) / None。"""
    if payload.get("spec") is not None:
        raw = payload["spec"]
        if isinstance(raw, dict):
            return raw
        if isinstance(raw, str) and raw.strip():
            return json.loads(raw)
    spec_path = str(payload.get("spec_path") or "").strip()
    if spec_path and ws_root is not None:
        from project_runtime.worker.tools import _within, resolve_task_path

        p = resolve_task_path(spec_path, ws_root)
        if not _within(p, ws_root):
            raise ValueError(f"spec_path 越界: {spec_path}")
        return json.loads(p.read_text(encoding="utf-8"))
    if spec_path:
        p = Path(spec_path)
        return json.loads(p.read_text(encoding="utf-8"))
    md = str(payload.get("markdown") or "")
    if md.strip():
        return md
    return None
