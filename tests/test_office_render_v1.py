"""O3：OfficeSpec v1 渲染观感加厚。"""

from __future__ import annotations

from pathlib import Path


def test_markdown_pptx_uses_thick_path(tmp_path: Path):
    """markdown 不得再走白版占位符（须封面色底 / 内容页色条）。"""
    from pptx import Presentation
    from pptx.enum.shapes import MSO_SHAPE

    from project_runtime.office.pptx_render import render_pptx_from_markdown

    out = tmp_path / "md.pptx"
    meta = render_pptx_from_markdown(
        "# 方案汇报\n## 要点\n- 一\n- 二\n## 结束\n- Q&A\n",
        out,
    )
    assert out.is_file()
    assert meta["slides"] >= 2
    prs = Presentation(str(out))
    # 封面：有实心矩形或背景；内容页：左侧色条矩形
    cover = prs.slides[0]
    cover_text = " ".join(
        sh.text_frame.text for sh in cover.shapes if sh.has_text_frame
    )
    assert "方案汇报" in cover_text
    assert "autogenerated" not in cover_text.lower()
    content = prs.slides[1]
    bars = [
        sh for sh in content.shapes
        if sh.shape_type == MSO_SHAPE.RECTANGLE
        and getattr(sh, "width", 0) and sh.width < 300000  # EMU，约 0.18"
    ]
    assert bars, "内容页应有左侧强调色条"


def test_pptx_v1_theme_and_layouts(tmp_path: Path):
    from project_runtime.office.pptx_render import render_pptx_from_spec

    out = tmp_path / "deck.pptx"
    meta = render_pptx_from_spec(
        {
            "spec_version": "1",
            "theme": {"preset": "business-blue"},
            "title": "方案汇报",
            "slides": [
                {"layout": "section", "title": "第一章"},
                {
                    "layout": "bullets",
                    "title": "要点",
                    "bullets": [
                        {"text": "一级", "level": 0},
                        {"text": "二级", "level": 1},
                    ],
                },
                {
                    "layout": "table",
                    "title": "数据",
                    "table": {
                        "headers": ["项", "值"],
                        "rows": [["A", "1"], ["B", "2"]],
                    },
                },
                {"layout": "closing", "title": "谢谢", "bullets": ["Q&A"]},
            ],
        },
        out,
    )
    assert out.is_file()
    assert meta["slides"] >= 4
    assert meta.get("non_empty_slides", 0) >= 3


def test_docx_v1_blocks_header_list(tmp_path: Path):
    from project_runtime.office.docx_render import render_docx_from_spec

    out = tmp_path / "doc.docx"
    meta = render_docx_from_spec(
        {
            "spec_version": "1",
            "theme": {"preset": "clean-gray"},
            "header": {"text": "内部资料"},
            "footer": {"text": "机密", "page_number": True},
            "cover": {"title": "年度报告", "subtitle": "摘要", "date": "2026"},
            "blocks": [
                {"type": "heading", "level": 1, "text": "概述"},
                {
                    "type": "paragraph",
                    "text": "首段正文。",
                    "indent": 0.74,
                    "spacing": 1.5,
                },
                {
                    "type": "list",
                    "ordered": False,
                    "items": ["甲", "乙"],
                },
                {"type": "page_break"},
                {"type": "heading", "level": 2, "text": "附录"},
            ],
        },
        out,
    )
    assert out.is_file()
    assert meta["headings"] >= 2
    assert meta["lists"] >= 2
    assert meta["paragraphs"] >= 1


def test_xlsx_v1_header_freeze(tmp_path: Path):
    from project_runtime.office.xlsx_render import render_xlsx_from_spec

    out = tmp_path / "book.xlsx"
    meta = render_xlsx_from_spec(
        {
            "sheets": [{
                "name": "销售",
                "data": [["品类", "金额"], ["A", 10], ["B", 20]],
                "header_style": {"fill": "1F4E79"},
                "col_widths": [16, 12],
                "freeze": "A2",
            }],
        },
        out,
    )
    assert out.is_file()
    assert meta["sheet_count"] == 1
